enum WTDataStatus: String, Codable {
    case complete
    case needsVerification = "needs-verification"
    var isComplete: Bool { self == .complete }
}

struct WTArea: Identifiable, Codable, Hashable {
    let id: String
    let name: String
    let description: String
    let imageEmoji: String
    let displayOrder: Int
}

struct WTCountry: Identifiable, Codable, Hashable {
    let id: String
    let name: String
    let localName: String?
    let areaId: String
    let description: String
    let imageEmoji: String
    let emojiFlag: String?
}

struct WTIngredient: Identifiable, Codable, Hashable {
    var id: String { "\(name)-\(displayOrder ?? 0)" }
    let name: String
    let quantity: Double?
    let unit: String?
    let notes: String?
    let isScalable: Bool?
    let displayOrder: Int?
    let recipeId: String?
    var scalable: Bool { isScalable ?? true }
}

struct WTStep: Identifiable, Codable, Hashable {
    var id: Int { stepNumber }
    let instruction: String
    let tip: String?
    let durationMinutes: Int?
    let stepNumber: Int
    let recipeId: String?
}

